      <h1>Privacy</h1>
      <p class="lead">What cyex.tv stores about you, and why. Last updated 2026/11/17.</p>
    </header>

    <p>The operator of cyex.tv is responsible for your data under the Swiss revised Federal Act on Data Protection (revFADP). We store as little as we can.</p>

    <h2>What is stored</h2>
    <ul>
      <li>Your Twitch and Kick platform user IDs, login names, display names and avatar URLs.</li>
      <li>The emotes you upload, with their metadata (name, tags, who uploaded them, when).</li>
      <li>Sessions: a cookie that keeps you signed in.</li>
      <li>Audit and report records: moderation actions, and reports you file or that are filed about you.</li>
    </ul>

    <h2>What is not stored</h2>
    <ul>
      <li>No email address. Kick's consent screen mentions email, but cyex.tv never reads it.</li>
      <li>No platform OAuth tokens. They are used once, at sign-in, and not kept.</li>
      <li>No ads, no third-party trackers, and no selling of data.</li>
    </ul>

    <h2>Why</h2>
    <p>To sign you in, show who made an emote, run the service, review uploads, handle reports and takedowns, and keep the site safe from abuse.</p>

    <h2>How long</h2>
    <ul>
      <li>Sessions expire. Signing out ends yours at once.</li>
      <li>To delete your account, write to <a class="link" href="mailto:privacy@cyex.tv">privacy@cyex.tv</a> from a channel you signed in with, or name it in your message. Its data is removed within 30 days.</li>
      <li>Backups rotate after 14 days, so deleted data is gone from them by then.</li>
    </ul>

    <h2>Where</h2>
    <p>The servers are in Finland. Emote images are served through Cloudflare's CDN, which sees the usual request details (such as the IP address) of people who load them.</p>

    <h2>Your rights</h2>
    <p>You can ask what we hold about you, ask us to correct or delete it, and object to its use. Write to <a class="link" href="mailto:privacy@cyex.tv">privacy@cyex.tv</a>. You may also complain to the Swiss Federal Data Protection and Information Commissioner (FDPIC).</p>

    <h2>Changes</h2>
    <p>If this page changes in a way that matters, the date at the top changes too.</p>
