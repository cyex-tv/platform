    <h2>General</h2>
    <p>Bugs and ideas go to the <a class="link" href="https://github.com/cyex-tv/platform/issues">issue tracker</a>. For anything else, write to <a class="link" href="mailto:abuse@cyex.tv">abuse@cyex.tv</a> and we will pass it on.</p>

    <h2>Abuse and takedowns</h2>
    <p>Email <a class="link" href="mailto:abuse@cyex.tv">abuse@cyex.tv</a>.</p>
    <p>If you use cyex.tv, report an emote from its page (Report, with a reason). Everyone else, including rights holders, people in an image and authorities, can email us with:</p>
    <ul>
      <li>the emote's URL (<code>https://cyex.tv/emotes/&lt;id&gt;</code>) or its CDN URL;</li>
      <li>what the problem is, and for copyright, what work it copies and that you hold the rights or act for whoever does;</li>
      <li>how to reach you.</li>
    </ul>
    <p>We answer within a few days, and act sooner on illegal content.</p>

    <h3>What a takedown does</h3>
    <ul>
      <li>The image is removed everywhere it is used, including every emote made from the same file.</li>
      <li>It leaves every set at once, and connected clients drop it live.</li>
      <li>It can't come back: re-uploads and near copies are refused.</li>
      <li>The files are deleted from storage and purged from the CDN cache.</li>
      <li>The owners are told, with the reason.</li>
    </ul>
    <p>The full process is in the <a class="link" href="https://github.com/cyex-tv/platform/blob/main/docs/takedown.md">takedown document</a>.</p>

    <h2>Privacy</h2>
